create table if not exists public.contact_inquiries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 120),
  work_email text not null check (char_length(work_email) between 3 and 254),
  brand_company text not null check (char_length(brand_company) between 1 and 160),
  work_model text not null check (work_model in ('OEM', 'ODM', 'Co-development', 'Not sure')),
  product_type text not null check (product_type in ('Creams', 'Lotions', 'Serums', 'Cleansers', 'Other')),
  other_product_type text check (other_product_type is null or char_length(other_product_type) <= 160),
  formula_status text check (formula_status is null or formula_status in ('Have one', 'Need one', 'Want to improve one')),
  quantity_estimate text,
  target_launch text check (target_launch is null or target_launch ~ '^20[0-9]{2}-(0[1-9]|1[0-2])$'),
  target_markets text[] not null default '{}',
  message text check (message is null or char_length(message) <= 3000),
  status text not null default 'new' check (status in ('new', 'in_review', 'contacted', 'closed', 'spam')),
  submission_key text not null unique check (char_length(submission_key) = 64),
  source_ip_hash text not null check (char_length(source_ip_hash) = 64),
  session_hash text not null check (char_length(session_hash) = 64),
  created_at timestamptz not null default now()
);

alter table public.contact_inquiries enable row level security;
alter table public.contact_inquiries force row level security;

revoke all on table public.contact_inquiries from anon, authenticated;
revoke all on sequence public.contact_inquiries_id_seq from anon, authenticated;
grant all on table public.contact_inquiries to service_role;
grant usage, select on sequence public.contact_inquiries_id_seq to service_role;

create or replace function public.submit_contact_inquiry(
  p_name text,
  p_work_email text,
  p_brand_company text,
  p_work_model text,
  p_product_type text,
  p_other_product_type text,
  p_formula_status text,
  p_quantity_estimate text,
  p_target_launch text,
  p_target_markets text[],
  p_message text,
  p_submission_key text,
  p_source_ip_hash text,
  p_session_hash text
) returns bigint
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  existing_id bigint;
  inserted_id bigint;
begin
  select id into existing_id from public.contact_inquiries where submission_key = p_submission_key;
  if existing_id is not null then return existing_id; end if;

  if (select count(*) from public.contact_inquiries
      where created_at > now() - interval '15 minutes'
        and (source_ip_hash = p_source_ip_hash or session_hash = p_session_hash)) >= 3 then
    raise exception using message = 'contact_rate_limited', errcode = 'P0001';
  end if;

  insert into public.contact_inquiries (
    name, work_email, brand_company, work_model, product_type,
    other_product_type, formula_status, quantity_estimate, target_launch,
    target_markets, message, submission_key, source_ip_hash, session_hash
  ) values (
    p_name, p_work_email, p_brand_company, p_work_model, p_product_type,
    nullif(p_other_product_type, ''), nullif(p_formula_status, ''),
    nullif(p_quantity_estimate, ''), nullif(p_target_launch, ''),
    coalesce(p_target_markets, '{}'), nullif(p_message, ''),
    p_submission_key, p_source_ip_hash, p_session_hash
  ) returning id into inserted_id;
  return inserted_id;
end;
$$;

revoke all on function public.submit_contact_inquiry(text, text, text, text, text, text, text, text, text, text[], text, text, text, text) from public, anon, authenticated;
grant execute on function public.submit_contact_inquiry(text, text, text, text, text, text, text, text, text, text[], text, text, text, text) to service_role;

comment on table public.contact_inquiries is 'Private website contact inquiries; no browser role has access.';
